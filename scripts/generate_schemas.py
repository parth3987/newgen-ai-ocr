"""Generate the documented output schemas from the code (docs/schemas/, docs/EXTRACTION_SCHEMAS.md).

Usage: python scripts/generate_schemas.py [--check]

Writes JSON Schema for the extraction result, the document-type schema format, each
built-in document type's validated record and the review formats (item, reviewed result,
correction request, history event, calibration), plus a Markdown reference of every built-in
document type. ``--check`` fails if any file differs (run by the test suite), so the
documented schemas cannot drift from what the API returns.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from newgen_ocr.extraction.models import ExtractionResult
from newgen_ocr.extraction.schema import DocumentSchema, SchemaRegistry
from newgen_ocr.extraction.validation import record_model, row_model
from newgen_ocr.review.models import (
    Calibration,
    CorrectionRequest,
    HistoryEvent,
    ReviewedResult,
    ReviewItem,
)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "schemas"
REFERENCE = ROOT / "docs" / "EXTRACTION_SCHEMAS.md"


def _json(data: object) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def reference(registry: SchemaRegistry) -> str:
    out = [
        "# Built-in document types",
        "",
        "Generated by `scripts/generate_schemas.py` from `src/newgen_ocr/extraction/schemas/`;",
        "do not edit by hand. Concepts and statuses: EXTRACTION.md. JSON Schemas of each",
        "validated record: `docs/schemas/records/`.",
    ]
    for schema in registry.schemas.values():
        out += ["", f"## `{schema.id}` (v{schema.version}): {schema.title}", "", schema.description]
        keywords = ", ".join(f"{k.text} ({k.weight:g})" for k in schema.classification.keywords)
        out += [
            "",
            f"Classification: minimum score {schema.classification.min_score:g}; "
            f"keywords {keywords}.",
        ]
        if schema.sections:
            sections = "; ".join(f"`{n}`: {', '.join(k)}" for n, k in schema.sections.items())
            out += ["", f"Sections: {sections}."]
        out += [
            "",
            "| Field | Type | Required | Labels | Section | Found by format | Sensitive |",
            "|---|---|---|---|---|---|---|",
        ]
        for f in schema.fields:
            section = (
                f"{f.section}" + (f" ({f.block} line)" if f.block else "") if f.section else ""
            )
            out.append(
                f"| `{f.name}` | {f.type.value} | {'yes' if f.required else ''} | "
                f"{', '.join(f.labels)} | {section} | {'yes' if f.scan else ''} | "
                f"{'yes' if f.sensitive else ''} |"
            )
        for table in schema.tables:
            out += ["", f"Table `{table.name}`{' (required)' if table.required else ''}:", ""]
            out += ["| Column | Type | Required | Header words |", "|---|---|---|---|"]
            for c in table.columns:
                out.append(
                    f"| `{c.name}` | {c.type.value} | {'yes' if c.required else ''} | "
                    f"{', '.join(c.headers)} |"
                )
        if schema.checks:
            out += ["", "| Check | Kind | Description |", "|---|---|---|"]
            for check in schema.checks:
                out.append(f"| `{check.id}` | {check.kind} | {check.description} |")
    return "\n".join(out) + "\n"


def expected_files() -> dict[Path, str]:
    registry = SchemaRegistry()
    files = {
        OUT / "extraction_result.schema.json": _json(ExtractionResult.model_json_schema()),
        OUT / "document_schema.schema.json": _json(DocumentSchema.model_json_schema()),
        REFERENCE: reference(registry),
        OUT / "review_item.schema.json": _json(ReviewItem.model_json_schema()),
        OUT / "reviewed_result.schema.json": _json(ReviewedResult.model_json_schema()),
        OUT / "correction_request.schema.json": _json(CorrectionRequest.model_json_schema()),
        OUT / "review_history_event.schema.json": _json(HistoryEvent.model_json_schema()),
        OUT / "calibration.schema.json": _json(Calibration.model_json_schema()),
    }
    for schema in registry.schemas.values():
        files[OUT / "records" / f"{schema.id}.schema.json"] = _json(
            record_model(schema).model_json_schema()
        )
        for table in schema.tables:
            files[OUT / "records" / f"{schema.id}.{table.name}.schema.json"] = _json(
                row_model(schema, table.name).model_json_schema()
            )
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in expected_files().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            sys.stdout.write(f"wrote {path.relative_to(ROOT)}\n")
    if stale:
        sys.stdout.write("stale (run scripts/generate_schemas.py): " + ", ".join(stale) + "\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
